/**
 * The tower movesets — one per element.
 *
 * Every tower is built to play like its element, not like a recoloured turret:
 *   - Air hovers over the pack cutting with its fans; Paper loops the field as a paper plane;
 *     Tempest drifts as a storm cloud to wherever the pack is thickest; Hunt leaves its den to
 *     run the lead husk down.
 *   - Water, Magma (a pirate ship firing broadsides) and Depths (a submarine) are naval and only
 *     stand in water.
 *   - Sound drums the towers around it faster, Psychic's board lets them see hidden husks,
 *     Technology overclocks the best of them, Life and Gold pay gold.
 *   - Shadow, Ruin and Cloth litter the road with traps; Conquest, Earth and Clay send troops
 *     and golems marching up it; Creation, Bind, Wax and Oil build sentries; Soul raises the
 *     fallen and Devotion converts the living.
 *   - Echo repeats every cast, Illusion mimics its neighbour, Death reaps the dying, Rubber
 *     ricochets, Plasma's beam ramps, Gunpowder shells wherever you point it.
 *
 * The five slots carry the element's real ability names (resolved from the element definition
 * at runtime unless overridden), its colours and statuses. Damage numbers are tier-0 values;
 * `TIER_DAMAGE_MULT` ramps them. Auras, zones and beams state damage per second.
 */

type Fx = TowerAbilityDef['fx'];
const ab = (damage: number, cooldown: number, fx: Fx, desc: string, extra: Partial<TowerAbilityDef> = {}): TowerAbilityDef =>
  ({ damage, cooldown, fx, desc, ...extra });

